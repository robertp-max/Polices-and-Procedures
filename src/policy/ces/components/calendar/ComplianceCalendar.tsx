import { useMemo, useState, useEffect } from 'react';
import { Repeat, RotateCcw, PenLine, Anchor } from 'lucide-react';
import { useCesTokens } from '../../theme';
import { useComplianceExecution } from '@/policy/compliance-execution';
import { usePmViewSprintStore } from '@/policy/pm/pmViewSprintStore';
import { useShellStore } from '@/policy/stores/uiStore';
import {
  type ComplianceDomain, type ComplianceEvent, type ExecutionUnit,
  COMPLIANCE_DOMAIN_LABEL,
} from '../../types';
import { UserAvatar } from '../primitives';

const DAY_MS = 24 * 60 * 60 * 1000;

const DOMAIN_TONE: Record<ComplianceDomain, { bg: string; fg: string }> = {
  clinical:   { bg: 'var(--ces-navy-soft)', fg: 'var(--ces-navy)' },
  compliance: { bg: 'var(--ces-orange-soft)', fg: 'var(--ces-orange)' },
  hr:         { bg: 'var(--ces-green-soft)',  fg: 'var(--ces-green)' },
  governance: { bg: 'var(--ces-amber-soft)',  fg: 'var(--ces-amber)' },
};

const FALLBACK_DOMAIN_TONE = DOMAIN_TONE.compliance;

function startOfDay(d: Date) { d.setHours(0,0,0,0); return d; }

function buildDays(startISO: string): Date[] {
  const start = startOfDay(new Date(startISO));
  return Array.from({ length: 14 }, (_, i) => new Date(start.getTime() + i * DAY_MS));
}

function sameDay(a: Date, b: Date) {
  return a.getFullYear() === b.getFullYear() && a.getMonth() === b.getMonth() && a.getDate() === b.getDate();
}

export function ComplianceCalendar() {
  const sprintWindow = usePmViewSprintStore(s => s.window);
  const snap = useComplianceExecution({ mode: 'sprint', window: sprintWindow });
  const EVENTS          = snap.events;
  const EXECUTION_UNITS = snap.executionUnits;

  const isLight = useShellStore(s => s.theme === 'care-indeed-light');
  const tokens = useCesTokens(); // CES tokens + light overrides: aware for no dark bleed in 14-day grid/pills (Image #4)

  const [viewportWidth, setViewportWidth] = useState(() => (typeof window === 'undefined' ? 1024 : window.innerWidth));
  const isMobileAgenda = viewportWidth < 640; // agenda primary on small screens, match designs, no bleed on 7-col grid

  useEffect(() => {
    const onResize = () => setViewportWidth(window.innerWidth);
    window.addEventListener('resize', onResize);
    return () => window.removeEventListener('resize', onResize);
  }, []);

  const days = useMemo(() => buildDays(sprintWindow.startDate), [sprintWindow.startDate]);
  const sprintEnd = useMemo(() => startOfDay(new Date(sprintWindow.endDate)), [sprintWindow.endDate]);

  const eventsByDay = useMemo(() => {
    const map = new Map<string, ComplianceEvent[]>();
    EVENTS.forEach(ev => {
      const k = ev.anchorDate.slice(0, 10);
      const arr = map.get(k) ?? [];
      arr.push(ev);
      map.set(k, arr);
    });
    return map;
  }, [EVENTS]);

  const sigWindowsByDay = useMemo(() => {
    const map = new Map<string, ExecutionUnit[]>();
    EXECUTION_UNITS
      .filter(u => u.complianceState === 'awaiting_signature')
      .forEach(u => {
        const k = u.dueDate.slice(0, 10);
        const arr = map.get(k) ?? [];
        arr.push(u);
        map.set(k, arr);
      });
    return map;
  }, [EXECUTION_UNITS]);

  const recurringByDay = useMemo(() => {
    const map = new Map<string, ComplianceEvent[]>();
    EVENTS.filter(e => e.category === 'recurring' || e.category === 'mandated').forEach(ev => {
      const k = ev.anchorDate.slice(0, 10);
      const arr = map.get(k) ?? [];
      arr.push(ev);
      map.set(k, arr);
    });
    return map;
  }, [EVENTS]);

  return (
    <div className="space-y-5">
      <div>
        <h1 className="text-[22px] font-bold" style={{ color: 'var(--ces-navy)' }}>
          Compliance Calendar
        </h1>
        <p className="text-[13px] mt-1" style={{ color: 'var(--ces-muted)' }}>
          14-day sprint window. Events anchor to mandated dates; signature windows surface SLA pressure; the retrospective day closes the cycle.
        </p>
      </div>

      {/* Legend */}
      <div className="flex flex-wrap gap-3 text-[11px]" style={{ color: 'var(--ces-muted)' }}>
        <Legend isLight={isLight} swatch="var(--ces-navy)"    label="Event Anchor" icon={<Anchor size={10} />} />
        <Legend isLight={isLight} swatch="var(--ces-orange)"  label="Signature Window" icon={<PenLine size={10} />} />
        <Legend isLight={isLight} swatch="var(--ces-amber)"   label="Recurring" icon={<Repeat size={10} />} />
        <Legend isLight={isLight} swatch="var(--ces-red)"     label="Retrospective" icon={<RotateCcw size={10} />} />
      </div>

      {/* Full bleed container for 14-day view to match Image #4, no CesCard perimeter bleed. Clean light grid, CES tokens. */}
      <div data-ces-calendar className="ces-calendar-grid rounded-xl overflow-hidden" style={{ background: 'var(--ces-white)', border: '1px solid var(--ces-border-soft)' }}>
        {isMobileAgenda ? (
          // Agenda primary on small screens (no bleed from grid-cols-7). Matches designs/images: list of anchored days first.
          <div data-ces-calendar className="ces-calendar-grid flex flex-col divide-y w-full max-w-full overflow-x-hidden" style={{ borderColor: 'transparent' }}>
            {days.map((day, _idx) => {
              const k = day.toISOString().slice(0, 10);
              const evs = eventsByDay.get(k) ?? [];
              const sigs = sigWindowsByDay.get(k) ?? [];
              const recurring = recurringByDay.get(k) ?? [];
              const isRetro = sameDay(day, sprintEnd);
              const isWkEnd = day.getDay() === 0 || day.getDay() === 6;
              return (
                <div key={k} className="p-2 flex items-start gap-2 text-[11px] calendar-day-cell" style={{ background: isRetro ? 'var(--ces-red-soft)' : isWkEnd ? 'var(--ces-canvas)' : 'var(--ces-white)' }}>
                  <div className="shrink-0 w-9 text-right font-mono tabular-nums" style={{ color: isRetro ? tokens.red : tokens.navy }}>{day.getDate()}</div>
                  <div className="min-w-0 flex-1">
                    {evs.length === 0 && sigs.length === 0 && !recurring.length && !isRetro ? (
                      <span style={{ color: tokens.muted, fontSize: '10px' }}>—</span>
                    ) : (
                      <>
                        {evs.map(ev => <div key={ev.id} className="truncate" style={{ color: (DOMAIN_TONE[ev.domain] ?? FALLBACK_DOMAIN_TONE).fg }}>{ev.title}</div>)}
                        {sigs.length > 0 && <div className="text-[10px] truncate" style={{ color: tokens.orange }}>Signature window</div>}
                        {recurring.length > 0 && <div className="text-[10px] truncate" style={{ color: tokens.amber }}>Recurring</div>}
                        {isRetro && <div className="text-[10px] font-bold uppercase" style={{ color: tokens.red }}>Retrospective</div>}
                      </>
                    )}
                  </div>
                </div>
              );
            })}
          </div>
        ) : (
          <>
            {/* Weekday header */}
            <div
              className="grid grid-cols-7 text-center text-[10px] font-bold uppercase tracking-[0.14em] py-2"
              style={{ background: 'var(--ces-canvas)', border: 'none', color: 'var(--ces-muted)' }}
            >
              {['Mon','Tue','Wed','Thu','Fri','Sat','Sun'].map(d => <span key={d}>{d}</span>)}
            </div>

            {/* 14-day grid (2 rows x 7 cols, Mon-aligned) — full bleed container, clean light grid per #4 */}
            <div data-ces-calendar className="ces-calendar-grid grid grid-cols-7" style={{ gridAutoRows: 'minmax(140px, auto)', border: 'none', width: '100%' }}>
              {days.map((day, idx) => {
                const k         = day.toISOString().slice(0, 10);
                const evs       = eventsByDay.get(k) ?? [];
                const sigs      = sigWindowsByDay.get(k) ?? [];
                const recurring = recurringByDay.get(k) ?? [];
                const isRetro   = sameDay(day, sprintEnd);
                const isWkEnd   = day.getDay() === 0 || day.getDay() === 6;
                return (
                  <CalendarDay
                    key={k}
                    day={day}
                    index={idx}
                    events={evs}
                    sigUnits={sigs}
                    hasRecurring={recurring.length > 0}
                    isRetro={isRetro}
                    isWeekend={isWkEnd}
                    isLight={isLight}
                  />
                );
              })}
            </div>
          </>
        )}
      </div>
    </div>
  );
}

