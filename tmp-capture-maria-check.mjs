import { chromium } from "playwright";
import fs from "fs";
import path from "path";
const base = "http://localhost:5173";
const outDir = path.join(process.cwd(), "tmp-screenshots");
fs.mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
await page.goto(base + "/journey/v1-journey", { waitUntil: "domcontentloaded", timeout: 30000 }).catch(()=>{});
await page.waitForTimeout(3000);
await page.screenshot({ path: path.join(outDir, "journey-v1-maria-check.png"), fullPage: true });
await page.goto(base + "/journey", { waitUntil: "domcontentloaded", timeout: 30000 }).catch(()=>{});
await page.waitForTimeout(3000);
await page.screenshot({ path: path.join(outDir, "journey-overview-maria-check.png"), fullPage: true });
await browser.close();
console.log("Captured latest with Maria Santos.");
