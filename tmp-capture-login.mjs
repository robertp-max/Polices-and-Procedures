import { chromium } from "playwright";
import fs from "fs";
import path from "path";
const base = "http://localhost:5173";
const outDir = path.join(process.cwd(), "tmp-screenshots");
fs.mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage();
console.log("Capturing /login");
await page.goto(base + "/login", { waitUntil: "domcontentloaded", timeout: 30000 }).catch(()=>{});
await page.waitForTimeout(2500);
await page.screenshot({ path: path.join(outDir, "login-page.png"), fullPage: true });
await browser.close();
console.log("Login page captured.");
